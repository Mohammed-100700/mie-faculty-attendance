// Google Apps Script code for Marks Management

export function getAppsScriptCode(webhookUrl, staffEmail, lecturerName) {
  var wh = webhookUrl || 'YOUR_BACKEND_URL/api/marks-sheets/webhook';
  var se = staffEmail || 'staff@example.com';
  var ln = lecturerName || 'Lecturer';

  return [
    '// ============================================',
    '// MIE Faculty Marks - Google Apps Script',
    '// ============================================',
    '',
    'var WEBHOOK_URL = "' + wh + '";',
    'var STAFF_EMAIL = "' + se + '";',
    'var LECTURER_NAME = "' + ln + '";',
    '',
    '// Adds custom menu when sheet opens',
    'function onOpen() {',
    '  SpreadsheetApp.getUi()',
    '    .createMenu("MIE Marks")',
    '    .addItem("Send Selected Columns", "sendSelected")',
    '    .addItem("Create Checkboxes", "createCheckboxes")',
    '    .addItem("Test Email", "testEmail")',
    '    .addItem("Setup Sheet Template", "setupTemplate")',
    '    .addToUi();',
    '',
    '// ============================================',
    '// SHEET TEMPLATE SETUP',
    '// Run once to create the recommended layout:',
    '//',
    '// Row 1: Branch name (merged across subject columns)',
    '// Row 2: Subject name (merged across test columns)',
    '// Row 3: Test names',
    '// Row 4: Checkboxes',
    '// Row 5+: Student names in col A, marks in data columns',
    '// ============================================',
    'function setupTemplate() {',
    '  var sheet = SpreadsheetApp.getActiveSpreadsheet().getActiveSheet();',
    '  var ui = SpreadsheetApp.getUi();',
    '',
    '  var response = ui.alert("Setup Template",',
    '    "This will set up a sample sheet layout with branches, subjects, and tests.\\n\\n" +',
    '    "Recommended structure:\\n" +',
    '    "  Row 1: Branch names (merged)\\n" +',
    '    "  Row 2: Subject names (merged)\\n" +',
    '    "  Row 3: Test names\\n" +',
    '    "  Row 4: Checkboxes\\n" +',
    '    "  Col A (Row 5+): Student names\\n\\n" +',
    '    "Continue?", ui.ButtonSet.YES_NO);',
    '',
    '  if (response !== ui.Button.YES) return;',
    '',
    '  // Clear sheet',
    '  sheet.clear();',
    '',
    '  // Sample data structure',
    '  // Row 1: Branches',
    '  sheet.getRange("A1").setValue("Student Name");',
    '  sheet.getRange("B1").setValue("Dhanmondi");',
    '  sheet.getRange("E1").setValue("Dhanmondi");',
    '  sheet.getRange("H1").setValue("Uttara");',
    '  sheet.getRange("K1").setValue("Uttara");',
    '',
    '  // Row 2: Subjects',
    '  sheet.getRange("B2").setValue("Mathematics");',
    '  sheet.getRange("E2").setValue("Physics");',
    '  sheet.getRange("H2").setValue("Mathematics");',
    '  sheet.getRange("K2").setValue("Physics");',
    '',
    '  // Row 3: Tests',
    '  sheet.getRange("B3").setValue("Quiz 1");',
    '  sheet.getRange("C3").setValue("Quiz 2");',
    '  sheet.getRange("D3").setValue("Midterm");',
    '  sheet.getRange("E3").setValue("Quiz 1");',
    '  sheet.getRange("F3").setValue("Quiz 2");',
    '  sheet.getRange("G3").setValue("Midterm");',
    '  sheet.getRange("H3").setValue("Quiz 1");',
    '  sheet.getRange("I3").setValue("Quiz 2");',
    '  sheet.getRange("J3").setValue("Midterm");',
    '  sheet.getRange("K3").setValue("Quiz 1");',
    '  sheet.getRange("L3").setValue("Quiz 2");',
    '  sheet.getRange("M3").setValue("Midterm");',
    '',
    '  // Row 4: Checkboxes',
    '  var checkbox = SpreadsheetApp.newDataValidation().requireCheckbox().build();',
    '  for (var c = 2; c <= 13; c++) {',
    '    var cell = sheet.getRange(4, c);',
    '    cell.setDataValidation(checkbox);',
    '    cell.setValue(false);',
    '    cell.setHorizontalAlignment("center");',
    '  }',
    '',
    '  // Sample students',
    '  var students = ["Ali Ahmed", "Sara Khan", "Mohammed Islam", "Fatima Begum", "Hassan Ali"];',
    '  for (var i = 0; i < students.length; i++) {',
    '    sheet.getRange(5 + i, 1).setValue(students[i]);',
    '  }',
    '',
    '  // Merge cells for branch headers',
    '  sheet.getRange("B1:D1").merge();',
    '  sheet.getRange("E1:G1").merge();',
    '  sheet.getRange("H1:J1").merge();',
    '  sheet.getRange("K1:M1").merge();',
    '',
    '  // Merge cells for subject headers',
    '  sheet.getRange("B2:D2").merge();',
    '  sheet.getRange("E2:G2").merge();',
    '  sheet.getRange("H2:J2").merge();',
    '  sheet.getRange("K2:M2").merge();',
    '',
    '  // Style headers',
    '  sheet.getRange("A1:M4").setFontWeight("bold");',
    '  sheet.getRange("B1:M1").setBackground("#2563eb").setFontColor("#fff");',
    '  sheet.getRange("B2:M2").setBackground("#dbeafe").setFontColor("#1e40af");',
    '  sheet.getRange("B3:M3").setBackground("#f1f5f9");',
    '  sheet.getRange("A1:M4").setHorizontalAlignment("center");',
    '  sheet.getRange("A5:A" + (4 + students.length)).setHorizontalAlignment("left");',
    '',
    '  // Auto-resize',
    '  sheet.autoResizeColumn(1);',
    '  for (var c = 2; c <= 13; c++) sheet.autoResizeColumn(c);',
    '',
    '  ui.alert("Template created!\\n\\n" +',
    '    "Structure:\\n" +',
    '    "  - Dhanmondi: Mathematics (Quiz 1, Quiz 2, Midterm)\\n" +',
    '    "  - Dhanmondi: Physics (Quiz 1, Quiz 2, Midterm)\\n" +',
    '    "  - Uttara: Mathematics (Quiz 1, Quiz 2, Midterm)\\n" +',
    '    "  - Uttara: Physics (Quiz 1, Quiz 2, Midterm)\\n\\n" +',
    '    "Add your own students and marks, then use MIE Marks > Send Selected Columns");',
    '}',
    '',
    '// ============================================',
    '// SEND SELECTED COLUMNS',
    '// ============================================',
    'function sendSelected() {',
    '  var sheet = SpreadsheetApp.getActiveSpreadsheet().getActiveSheet();',
    '  var lastCol = sheet.getLastColumn();',
    '  var lastRow = sheet.getLastRow();',
    '',
    '  if (lastCol < 2 || lastRow < 5) {',
    '    SpreadsheetApp.getUi().alert("Sheet is empty. Add data first or run Setup Sheet Template.");',
    '    return;',
    '  }',
    '',
    '  // Find checked columns and group by branch + subject',
    '  var selectedColumns = [];',
    '  for (var c = 2; c <= lastCol; c++) {',
    '    var isChecked = sheet.getRange(4, c).getValue();',
    '    if (isChecked !== true) continue;',
    '',
    '    var testName = sheet.getRange(3, c).getValue();',
    '    var subjectName = sheet.getRange(2, c).getValue();',
    '    var branchName = sheet.getRange(1, c).getValue();',
    '',
    '    if (!testName) continue;',
    '',
    '    // Collect student marks for this column',
    '    var students = [];',
    '    for (var r = 5; r <= lastRow; r++) {',
    '      var name = sheet.getRange(r, 1).getValue();',
    '      var mark = sheet.getRange(r, c).getValue();',
    '      if (name) {',
    '        students.push({ name: name, mark: mark !== "" ? mark : "-" });',
    '      }',
    '    }',
    '',
    '    selectedColumns.push({',
    '      branch: branchName || "Unknown",',
    '      subject: subjectName || "Unknown",',
    '      test: testName,',
    '      students: students',
    '    });',
    '  }',
    '',
    '  if (selectedColumns.length === 0) {',
    '    SpreadsheetApp.getUi().alert("No columns selected. Check the boxes in row 4 for the columns you want to send.");',
    '    return;',
    '  }',
    '',
    '  if (!STAFF_EMAIL || STAFF_EMAIL === "staff@example.com") {',
    '    SpreadsheetApp.getUi().alert("STAFF_EMAIL not set. Edit the script and set your staff email.");',
    '    return;',
    '  }',
    '',
    '  // Group by Branch > Subject',
    '  var groups = {};',
    '  for (var i = 0; i < selectedColumns.length; i++) {',
    '    var col = selectedColumns[i];',
    '    var key = col.branch + "|" + col.subject;',
    '    if (!groups[key]) {',
    '      groups[key] = { branch: col.branch, subject: col.subject, tests: [] };',
    '    }',
    '    groups[key].tests.push(col);',
    '  }',
    '',
    '  // Build email subject',
    '  var subject = "Marks Update - " + LECTURER_NAME + " - " + selectedColumns.length + " Test(s)";',
    '',
    '  // Build email body',
    '  var html = buildEmailBody(groups, selectedColumns);',
    '',
    '  MailApp.sendEmail({',
    '    to: STAFF_EMAIL,',
    '    subject: subject,',
    '    htmlBody: html',
    '  });',
    '',
    '  // Sync to dashboard',
    '  syncToDashboard(sheet, lastCol);',
    '',
    '  SpreadsheetApp.getUi().alert("Email sent to " + STAFF_EMAIL + "\\n" + selectedColumns.length + " test(s) across " + Object.keys(groups).length + " group(s).");',
    '}',
    '',
    'function buildEmailBody(groups, selectedColumns) {',
    '  var groupKeys = Object.keys(groups);',
    '  var totalStudents = selectedColumns[0].students.length;',
    '',
    '  // Count total tests per group for summary',
    '  var summaryLine = "";',
    '  for (var g = 0; g < groupKeys.length; g++) {',
    '    var grp = groups[groupKeys[g]];',
    '    if (g > 0) summaryLine += " &bull; ";',
    '    summaryLine += grp.branch + " / " + grp.subject + " (" + grp.tests.length + ")";',
    '  }',
    '',
    '  // Header',
    '  var html = "<div style=\\"font-family:Segoe UI,Arial,sans-serif;max-width:700px;margin:0 auto;border:1px solid #e2e8f0;border-radius:8px;overflow:hidden;\\">";',
    '  html += "<div style=\\"background:linear-gradient(135deg,#2563eb,#1d4ed8);color:#fff;padding:20px 24px;\\">";',
    '  html += "<h2 style=\\"margin:0;font-size:18px;letter-spacing:-0.3px;\\">Marks Update</h2>";',
    '  html += "<p style=\\"margin:4px 0 0;opacity:0.85;font-size:13px;\\">" + LECTURER_NAME + " &bull; " + new Date().toLocaleDateString() + "</p>";',
    '  html += "<p style=\\"margin:6px 0 0;opacity:0.7;font-size:12px;\\">" + summaryLine + "</p>";',
    '  html += "</div>";',
    '',
    '  // Each group (Branch + Subject) gets a section',
    '  for (var g = 0; g < groupKeys.length; g++) {',
    '    var grp = groups[groupKeys[g]];',
    '    var numTests = grp.tests.length;',
    '    var numStudents = grp.tests[0].students.length;',
    '',
    '    // Group header',
    '    html += "<div style=\\"padding:14px 20px;background:#f8fafc;border-top:1px solid #e2e8f0;\\">";',
    '    html += "<div style=\\"display:inline-block;background:#2563eb;color:#fff;padding:3px 10px;border-radius:4px;font-size:11px;font-weight:600;margin-right:8px;\\">" + grp.branch + "</div>";',
    '    html += "<div style=\\"display:inline-block;background:#dbeafe;color:#1e40af;padding:3px 10px;border-radius:4px;font-size:11px;font-weight:600;\\">" + grp.subject + "</div>";',
    '    html += "</div>";',
    '',
    '    // Build vertical table: students = rows, tests = columns',
    '    // Header row with test names',
    '    html += "<table style=\\"width:100%;border-collapse:collapse;\\">";',
    '    html += "<thead><tr style=\\"background:#f1f5f9;\\">";',
    '    html += "<th style=\\"padding:10px 14px;text-align:left;border:1px solid #e2e8f0;font-size:12px;color:#475569;font-weight:600;\\">Student</th>";',
    '    for (var t = 0; t < numTests; t++) {',
    '      html += "<th style=\\"padding:10px 14px;text-align:center;border:1px solid #e2e8f0;font-size:12px;color:#475569;font-weight:600;min-width:70px;\\">" + grp.tests[t].test + "</th>";',
    '    }',
    '    html += "</tr></thead>";',
    '',
    '    // Data rows',
    '    html += "<tbody>";',
    '    for (var r = 0; r < numStudents; r++) {',
    '      var bg = r % 2 === 0 ? "#ffffff" : "#f8fafc";',
    '      html += "<tr style=\\"background:" + bg + "\\">";',
    '      html += "<td style=\\"padding:10px 14px;border:1px solid #e2e8f0;font-weight:600;color:#1e293b;\\">" + grp.tests[0].students[r].name + "</td>";',
    '      for (var t = 0; t < numTests; t++) {',
    '        var mark = grp.tests[t].students[r] ? grp.tests[t].students[r].mark : "-";',
    '        html += "<td style=\\"padding:10px 14px;border:1px solid #e2e8f0;text-align:center;font-weight:500;color:#2563eb;\\">" + mark + "</td>";',
    '      }',
    '      html += "</tr>";',
    '    }',
    '    html += "</tbody></table>";',
    '  }',
    '',
    '  // Footer',
    '  html += "<p style=\\"color:#94a3b8;font-size:11px;margin:0;padding:10px 16px;background:#f8fafc;border-top:1px solid #e2e8f0;\\">";',
    '  html += "MIE Faculty Attendance System &bull; " + totalStudents + " student(s) &bull; " + selectedColumns.length + " test(s)";',
    '  html += "</p></div>";',
    '',
    '  return html;',
    '}',
    '',
    'function syncToDashboard(sheet, lastCol) {',
    '  if (!WEBHOOK_URL || WEBHOOK_URL.indexOf("YOUR_BACKEND_URL") !== -1) return;',
    '  var sheetId = sheet.getParent().getId();',
    '  var columns = [];',
    '  for (var c = 2; c <= lastCol; c++) {',
    '    var testName = sheet.getRange(3, c).getValue();',
    '    var subjectName = sheet.getRange(2, c).getValue();',
    '    var branchName = sheet.getRange(1, c).getValue();',
    '    var isApproved = sheet.getRange(4, c).getValue() === true;',
    '    if (testName) {',
    '      columns.push({',
    '        name: testName,',
    '        subject: subjectName || "",',
    '        branch: branchName || "",',
    '        colIndex: c,',
    '        approved: isApproved,',
    '        approvedAt: isApproved ? new Date().toISOString() : null',
    '      });',
    '    }',
    '  }',
    '  try {',
    '    UrlFetchApp.fetch(WEBHOOK_URL, {',
    '      method: "post",',
    '      contentType: "application/json",',
    '      payload: JSON.stringify({ sheetId: sheetId, columns: columns })',
    '    });',
    '  } catch (err) {',
    '    // silent fail',
    '  }',
    '}',
    '',
    '// Create checkboxes in row 4',
    'function createCheckboxes() {',
    '  var sheet = SpreadsheetApp.getActiveSpreadsheet().getActiveSheet();',
    '  var lastCol = sheet.getLastColumn();',
    '  if (lastCol < 2) {',
    '    SpreadsheetApp.getUi().alert("No columns found. Run Setup Sheet Template first or add test names in row 3.");',
    '    return;',
    '  }',
    '  var checkbox = SpreadsheetApp.newDataValidation().requireCheckbox().build();',
    '  for (var c = 2; c <= lastCol; c++) {',
    '    var cell = sheet.getRange(4, c);',
    '    cell.setDataValidation(checkbox);',
    '    cell.setValue(false);',
    '    cell.setHorizontalAlignment("center");',
    '  }',
    '  SpreadsheetApp.getUi().alert("Done! Checkboxes created in row 4 for " + (lastCol - 1) + " columns.");',
    '}',
    '',
    '// Test email',
    'function testEmail() {',
    '  if (!STAFF_EMAIL || STAFF_EMAIL === "staff@example.com") {',
    '    SpreadsheetApp.getUi().alert("Set STAFF_EMAIL first!");',
    '    return;',
    '  }',
    '  MailApp.sendEmail({',
    '    to: STAFF_EMAIL,',
    '    subject: "Test Email - MIE Faculty System",',
    '    htmlBody: "<div style=\\"font-family:Arial;padding:20px;\\"><h2 style=\\"color:#2563eb;\\">Test Successful!</h2><p>Email is configured correctly for " + LECTURER_NAME + ".</p></div>"',
    '  });',
    '  SpreadsheetApp.getUi().alert("Test email sent to " + STAFF_EMAIL);',
    '}',
  ].join('\n');
}
