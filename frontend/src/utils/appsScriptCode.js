// Google Apps Script code for Marks Management

export function getAppsScriptCode(webhookUrl, staffEmail, lecturerName) {
  var wh = webhookUrl || 'YOUR_BACKEND_URL/api/marks-sheets/webhook';
  var se = staffEmail || 'staff@example.com';
  var ln = lecturerName || 'Lecturer';

  return [
    '// ============================================',
    '// MIE Faculty Marks - Google Apps Script',
    '// ============================================',
    '',
    '// --- CONFIGURATION ---',
    'var WEBHOOK_URL = "' + wh + '";',
    'var STAFF_EMAIL = "' + se + '";',
    'var LECTURER_NAME = "' + ln + '";',
    '',
    '// Auto-run on any edit',
    'function onEdit(e) {',
    '  if (!e || !e.source) return;',
    '  var sheet = e.source.getActiveSheet();',
    '  var range = e.range;',
    '  var row = range.getRow();',
    '  var col = range.getColumn();',
    '',
    '  // Only react to row 2 (checkbox row), columns B onwards',
    '  if (row !== 2 || col < 2) return;',
    '',
    '  // Only react when checkbox is CHECKED (not unchecked)',
    '  if (range.getValue() !== true) return;',
    '',
    '  // Get the test name from row 1',
    '  var testName = sheet.getRange(1, col).getValue();',
    '  if (!testName) return;',
    '',
    '  // Collect student names and marks for THIS column only',
    '  var lastRow = sheet.getLastRow();',
    '  var students = [];',
    '  for (var r = 3; r <= lastRow; r++) {',
    '    var name = sheet.getRange(r, 1).getValue();',
    '    var mark = sheet.getRange(r, col).getValue();',
    '    if (name) {',
    '      students.push({ name: name, mark: mark !== "" ? mark : "-" });',
    '    }',
    '  }',
    '',
    '  // Sync ALL column statuses to dashboard',
    '  syncToDashboard(sheet);',
    '',
    '  // Send email for THIS column',
    '  sendColumnEmail(testName, students);',
    '}',
    '',
    'function syncToDashboard(sheet) {',
    '  if (!WEBHOOK_URL || WEBHOOK_URL.indexOf("YOUR_BACKEND_URL") !== -1) return;',
    '  var sheetId = sheet.getParent().getId();',
    '  var lastCol = sheet.getLastColumn();',
    '  var columns = [];',
    '  for (var c = 2; c <= lastCol; c++) {',
    '    var colName = sheet.getRange(1, c).getValue();',
    '    var isApproved = sheet.getRange(2, c).getValue() === true;',
    '    if (colName) {',
    '      columns.push({',
    '        name: colName,',
    '        colIndex: c,',
    '        approved: isApproved,',
    '        approvedAt: isApproved ? new Date().toISOString() : null',
    '      });',
    '    }',
    '  }',
    '  try {',
    '    UrlFetchApp.fetch(WEBHOOK_URL, {',
    '      method: "post",',
    '      contentType: "application/json",',
    '      payload: JSON.stringify({ sheetId: sheetId, columns: columns })',
    '    });',
    '  } catch (err) {',
    '    // silent fail',
    '  }',
    '}',
    '',
    'function sendColumnEmail(testName, students) {',
    '  if (!STAFF_EMAIL || STAFF_EMAIL === "staff@example.com") return;',
    '',
    '  var subject = "Marks Approved: " + testName + " - " + LECTURER_NAME;',
    '',
    '  // Build styled HTML table',
    '  var tableRows = "";',
    '  for (var i = 0; i < students.length; i++) {',
    '    var bg = i % 2 === 0 ? "#ffffff" : "#f8f9fa";',
    '    tableRows += "<tr style=\\"background:" + bg + "\\">";',
    '    tableRows += "<td style=\\"padding:10px 14px;border:1px solid #e0e0e0;font-weight:600;\\">" + students[i].name + "</td>";',
    '    tableRows += "<td style=\\"padding:10px 14px;border:1px solid #e0e0e0;text-align:center;font-weight:500;color:#2563eb;\\">" + students[i].mark + "</td>";',
    '    tableRows += "</tr>";',
    '  }',
    '',
    '  var html = "<div style=\\"font-family:Segoe UI,Arial,sans-serif;max-width:500px;margin:0 auto;\\">";',
    '  html += "<div style=\\"background:linear-gradient(135deg,#2563eb,#1d4ed8);color:#fff;padding:20px 24px;border-radius:8px 8px 0 0;\\">";',
    '  html += "<h2 style=\\"margin:0;font-size:18px;\\">Marks Approved</h2>";',
    '  html += "<p style=\\"margin:4px 0 0;opacity:0.9;font-size:13px;\\">" + LECTURER_NAME + " - " + new Date().toLocaleDateString() + "</p>";',
    '  html += "</div>";',
    '  html += "<div style=\\"background:#f0f7ff;padding:14px 24px;border-left:4px solid #2563eb;margin:0;\\">";',
    '  html += "<strong style=\\"color:#1e40af;font-size:15px;\\">" + testName + "</strong>";',
    '  html += "</div>";',
    '  html += "<table style=\\"width:100%;border-collapse:collapse;border:1px solid #e0e0e0;border-top:none;\\">";',
    '  html += "<thead><tr style=\\"background:#f1f5f9;\\">";',
    '  html += "<th style=\\"padding:10px 14px;text-align:left;border:1px solid #e0e0e0;font-size:13px;color:#475569;\\">Student</th>";',
    '  html += "<th style=\\"padding:10px 14px;text-align:center;border:1px solid #e0e0e0;font-size:13px;color:#475569;width:80px;\\">Mark</th>";',
    '  html += "</tr></thead>";',
    '  html += "<tbody>" + tableRows + "</tbody>";',
    '  html += "</table>";',
    '  html += "<p style=\\"color:#94a3b8;font-size:11px;margin:12px 0 0;padding:0 4px;\\">MIE Faculty Attendance System - Automated</p>";',
    '  html += "</div>";',
    '',
    '  MailApp.sendEmail({',
    '    to: STAFF_EMAIL,',
    '    subject: subject,',
    '    htmlBody: html',
    '  });',
    '}',
    '',
    '// ============================================',
    '// SETUP - Run these once from Apps Script editor',
    '// ============================================',
    '',
    '// Step 1: Create checkboxes in row 2',
    'function createCheckboxes() {',
    '  var sheet = SpreadsheetApp.getActiveSpreadsheet().getActiveSheet();',
    '  var lastCol = sheet.getLastColumn();',
    '  if (lastCol < 2) {',
    '    SpreadsheetApp.getUi().alert("No test columns found. Add test names in row 1 first (starting from column B).");',
    '    return;',
    '  }',
    '  var checkbox = SpreadsheetApp.newDataValidation().requireCheckbox().build();',
    '  for (var c = 2; c <= lastCol; c++) {',
    '    var cell = sheet.getRange(2, c);',
    '    cell.setDataValidation(checkbox);',
    '    cell.setValue(false);',
    '    cell.setHorizontalAlignment("center");',
    '  }',
    '  SpreadsheetApp.getUi().alert("Done! Checkboxes created in row 2 for " + (lastCol - 1) + " test columns.");',
    '}',
    '',
    '// Step 2: Test email (sends a sample to verify it works)',
    'function testEmail() {',
    '  if (!STAFF_EMAIL || STAFF_EMAIL === "staff@example.com") {',
    '    SpreadsheetApp.getUi().alert("Set STAFF_EMAIL first!");',
    '    return;',
    '  }',
    '  MailApp.sendEmail({',
    '    to: STAFF_EMAIL,',
    '    subject: "Test Email - MIE Faculty System",',
    '    htmlBody: "<h2>Test successful!</h2><p>Email is configured correctly.</p>"',
    '  });',
    '  SpreadsheetApp.getUi().alert("Test email sent to " + STAFF_EMAIL);',
    '}',
  ].join('\n');
}
