// Google Apps Script code for Marks Management

export function getAppsScriptCode(webhookUrl, staffEmail, lecturerName) {
  var wh = webhookUrl || 'YOUR_BACKEND_URL/api/marks-sheets/webhook';
  var se = staffEmail || 'staff@example.com';
  var ln = lecturerName || 'Lecturer';

  return [
    '// ============================================',
    '// MIE Faculty Marks - Google Apps Script',
    '// ============================================',
    '',
    'var WEBHOOK_URL = "' + wh + '";',
    'var STAFF_EMAIL = "' + se + '";',
    'var LECTURER_NAME = "' + ln + '";',
    '',
    '// Adds custom menu when workbook opens',
    'function onOpen() {',
    '  SpreadsheetApp.getUi()',
    '    .createMenu("MIE Marks")',
    '    .addItem("Send Selected Columns", "sendSelected")',
    '    .addItem("Setup Current Sheet", "setupCurrentSheet")',
    '    .addItem("Setup All Batch Sheets", "setupAllSheets")',
    '    .addItem("Test Email", "testEmail")',
    '    .addToUi();',
    '',
    '// ============================================',
    '// SETUP FUNCTIONS',
    '// ============================================',
    '',
    '// Setup all 3 batch sheets at once',
    'function setupAllSheets() {',
    '  var ss = SpreadsheetApp.getActiveSpreadsheet();',
    '  var ui = SpreadsheetApp.getUi();',
    '',
    '  var batches = ["September", "December", "March"];',
    '  var branches = ["Dhanmondi", "Uttara"];',
    '  var subjects = ["Mathematics", "Physics"];',
    '  var tests = ["Quiz 1", "Quiz 2", "Midterm"];',
    '  var sampleStudents = ["Ali Ahmed", "Sara Khan", "Mohammed Islam", "Fatima Begum", "Hassan Ali"];',
    '',
    '  for (var b = 0; b < batches.length; b++) {',
    '    var sheet = ss.getSheetByName(batches[b]);',
    '    if (!sheet) {',
    '      sheet = ss.insertSheet(batches[b]);',
    '    }',
    '    setupSheet(sheet, branches, subjects, tests, sampleStudents);',
    '  }',
    '',
    '  // Activate September sheet',
    '  ss.setActiveSheet(ss.getSheetByName("September"));',
    '',
    '  ui.alert("All 3 batch sheets created!\\n\\n" +',
    '    "Sheets: September, December, March\\n" +',
    '    "Each sheet has:\\n" +',
    '    "  - Dhanmondi: Mathematics + Physics\\n" +',
    '    "  - Uttara: Mathematics + Physics\\n" +',
    '    "  - 3 tests each (Quiz 1, Quiz 2, Midterm)\\n\\n" +',
    '    "Switch between sheets using tabs at the bottom.\\n" +',
    '    "Fill in your marks, then use MIE Marks > Send Selected Columns");',
    '}',
    '',
    '// Setup current active sheet',
    'function setupCurrentSheet() {',
    '  var sheet = SpreadsheetApp.getActiveSpreadsheet().getActiveSheet();',
    '  var ui = SpreadsheetApp.getUi();',
    '  var branches = ["Dhanmondi", "Uttara"];',
    '  var subjects = ["Mathematics", "Physics"];',
    '  var tests = ["Quiz 1", "Quiz 2", "Midterm"];',
    '  var sampleStudents = ["Ali Ahmed", "Sara Khan", "Mohammed Islam", "Fatima Begum", "Hassan Ali"];',
    '  setupSheet(sheet, branches, subjects, tests, sampleStudents);',
    '  ui.alert("Sheet setup complete for: " + sheet.getName());',
    '}',
    '',
    '// Setup a single sheet with the standard layout',
    'function setupSheet(sheet, branches, subjects, tests, students) {',
    '  sheet.clear();',
    '',
    '  // Calculate columns: 1 (student name) + branches * subjects * tests',
    '  var col = 2;',
    '  var checkbox = SpreadsheetApp.newDataValidation().requireCheckbox().build();',
    '',
    '  // Row 1: Branch headers (merged)',
    '  sheet.getRange("A1").setValue("Student Name");',
    '  for (var b = 0; b < branches.length; b++) {',
    '    var startCol = col;',
    '    var endCol = col + subjects.length * tests.length - 1;',
    '    sheet.getRange(1, startCol, 1, endCol - startCol + 1).merge();',
    '    sheet.getRange(1, startCol).setValue(branches[b]);',
    '    col = endCol + 1;',
    '  }',
    '',
    '  // Row 2: Subject headers (merged per subject)',
    '  col = 2;',
    '  for (var b = 0; b < branches.length; b++) {',
    '    for (var s = 0; s < subjects.length; s++) {',
    '      var startCol = col;',
    '      var endCol = col + tests.length - 1;',
    '      sheet.getRange(2, startCol, 1, endCol - startCol + 1).merge();',
    '      sheet.getRange(2, startCol).setValue(subjects[s]);',
    '      col = endCol + 1;',
    '    }',
    '  }',
    '',
    '  // Row 3: Test names + Row 4: Checkboxes',
    '  col = 2;',
    '  for (var b = 0; b < branches.length; b++) {',
    '    for (var s = 0; s < subjects.length; s++) {',
    '      for (var t = 0; t < tests.length; t++) {',
    '        sheet.getRange(3, col).setValue(tests[t]);',
    '        var cell = sheet.getRange(4, col);',
    '        cell.setDataValidation(checkbox);',
    '        cell.setValue(false);',
    '        cell.setHorizontalAlignment("center");',
    '        col++;',
    '      }',
    '    }',
    '  }',
    '',
    '  // Student names',
    '  for (var i = 0; i < students.length; i++) {',
    '    sheet.getRange(5 + i, 1).setValue(students[i]);',
    '  }',
    '',
    '  // Style everything',
    '  sheet.getRange("A1").setFontWeight("bold").setBackground("#1e293b").setFontColor("#fff");',
    '  sheet.getRange(1, 2, 1, col - 2).setBackground("#2563eb").setFontColor("#fff").setFontWeight("bold");',
    '  sheet.getRange(2, 2, 1, col - 2).setBackground("#dbeafe").setFontColor("#1e40af").setFontWeight("bold");',
    '  sheet.getRange(3, 2, 1, col - 2).setBackground("#f1f5f9").setFontWeight("bold");',
    '  sheet.getRange("A1:" + sheet.getRange(4, col - 1).getA1Notation()).setHorizontalAlignment("center");',
    '  sheet.getRange("A5:A" + (4 + students.length)).setHorizontalAlignment("left").setFontWeight("bold");',
    '',
    '  // Auto-resize',
    '  sheet.autoResizeColumn(1);',
    '  for (var c = 2; c < col; c++) sheet.autoResizeColumn(c);',
    '  sheet.setFrozenRows(4);',
    '}',
    '',
    '// ============================================',
    '// SEND SELECTED COLUMNS',
    '// ============================================',
    'function sendSelected() {',
    '  var sheet = SpreadsheetApp.getActiveSpreadsheet().getActiveSheet();',
    '  var sheetName = sheet.getName();',
    '  var lastCol = sheet.getLastColumn();',
    '  var lastRow = sheet.getLastRow();',
    '',
    '  if (lastCol < 2 || lastRow < 5) {',
    '    SpreadsheetApp.getUi().alert("Sheet is empty. Run Setup Current Sheet first.");',
    '    return;',
    '  }',
    '',
    '  // Find checked columns and read branch/subject context',
    '  var selectedColumns = [];',
    '  for (var c = 2; c <= lastCol; c++) {',
    '    var isChecked = sheet.getRange(4, c).getValue();',
    '    if (isChecked !== true) continue;',
    '',
    '    var testName = sheet.getRange(3, c).getValue();',
    '    var subjectName = sheet.getRange(2, c).getValue();',
    '    var branchName = sheet.getRange(1, c).getValue();',
    '    if (!testName) continue;',
    '',
    '    var students = [];',
    '    for (var r = 5; r <= lastRow; r++) {',
    '      var name = sheet.getRange(r, 1).getValue();',
    '      var mark = sheet.getRange(r, c).getValue();',
    '      if (name) students.push({ name: name, mark: mark !== "" ? mark : "-" });',
    '    }',
    '',
    '    selectedColumns.push({',
    '      branch: branchName || "Unknown",',
    '      subject: subjectName || "Unknown",',
    '      test: testName,',
    '      students: students',
    '    });',
    '  }',
    '',
    '  if (selectedColumns.length === 0) {',
    '    SpreadsheetApp.getUi().alert("No columns selected. Check boxes in row 4 for columns to send.");',
    '    return;',
    '  }',
    '',
    '  if (!STAFF_EMAIL || STAFF_EMAIL === "staff@example.com") {',
    '    SpreadsheetApp.getUi().alert("STAFF_EMAIL not set.");',
    '    return;',
    '  }',
    '',
    '  // Group by Branch > Subject',
    '  var groups = {};',
    '  for (var i = 0; i < selectedColumns.length; i++) {',
    '    var col = selectedColumns[i];',
    '    var key = col.branch + "|" + col.subject;',
    '    if (!groups[key]) groups[key] = { branch: col.branch, subject: col.subject, tests: [] };',
    '    groups[key].tests.push(col);',
    '  }',
    '',
    '  var subject = "Marks: " + sheetName + " Batch - " + LECTURER_NAME;',
    '  var html = buildEmailBody(groups, selectedColumns, sheetName);',
    '',
    '  MailApp.sendEmail({ to: STAFF_EMAIL, subject: subject, htmlBody: html });',
    '',
    '  syncToDashboard(sheet, lastCol);',
    '  SpreadsheetApp.getUi().alert("Email sent to " + STAFF_EMAIL + "\\n" + selectedColumns.length + " test(s) from " + sheetName + " batch.");',
    '}',
    '',
    'function buildEmailBody(groups, selectedColumns, sheetName) {',
    '  var groupKeys = Object.keys(groups);',
    '  var totalStudents = selectedColumns[0].students.length;',
    '',
    '  var html = "<div style=\\"font-family:Segoe UI,Arial,sans-serif;max-width:700px;margin:0 auto;border:1px solid #e2e8f0;border-radius:8px;overflow:hidden;\\">";',
    '',
    '  // Header with batch name',
    '  html += "<div style=\\"background:linear-gradient(135deg,#2563eb,#1d4ed8);color:#fff;padding:20px 24px;\\">";',
    '  html += "<h2 style=\\"margin:0;font-size:18px;\\">Marks Update</h2>";',
    '  html += "<p style=\\"margin:4px 0 0;opacity:0.85;font-size:13px;\\">" + LECTURER_NAME + " &bull; " + sheetName + " Batch &bull; " + new Date().toLocaleDateString() + "</p>";',
    '  html += "</div>";',
    '',
    '  // Each group (Branch + Subject) gets a section',
    '  for (var g = 0; g < groupKeys.length; g++) {',
    '    var grp = groups[groupKeys[g]];',
    '    var numTests = grp.tests.length;',
    '    var numStudents = grp.tests[0].students.length;',
    '',
    '    // Group header with branch + subject badges',
    '    html += "<div style=\\"padding:12px 20px;background:#f8fafc;border-top:1px solid #e2e8f0;\\">";',
    '    html += "<span style=\\"display:inline-block;background:#2563eb;color:#fff;padding:3px 10px;border-radius:4px;font-size:11px;font-weight:600;margin-right:6px;\\">" + grp.branch + "</span>";',
    '    html += "<span style=\\"display:inline-block;background:#dbeafe;color:#1e40af;padding:3px 10px;border-radius:4px;font-size:11px;font-weight:600;\\">" + grp.subject + "</span>";',
    '    html += "</div>";',
    '',
    '    // Vertical table: students = rows, tests = columns',
    '    html += "<table style=\\"width:100%;border-collapse:collapse;\\">";',
    '    html += "<thead><tr style=\\"background:#f1f5f9;\\">";',
    '    html += "<th style=\\"padding:10px 14px;text-align:left;border:1px solid #e2e8f0;font-size:12px;color:#475569;font-weight:600;\\">Student</th>";',
    '    for (var t = 0; t < numTests; t++) {',
    '      html += "<th style=\\"padding:10px 14px;text-align:center;border:1px solid #e2e8f0;font-size:12px;color:#475569;font-weight:600;min-width:70px;\\">" + grp.tests[t].test + "</th>";',
    '    }',
    '    html += "</tr></thead><tbody>";',
    '',
    '    for (var r = 0; r < numStudents; r++) {',
    '      var bg = r % 2 === 0 ? "#ffffff" : "#f8fafc";',
    '      html += "<tr style=\\"background:" + bg + "\\">";',
    '      html += "<td style=\\"padding:10px 14px;border:1px solid #e2e8f0;font-weight:600;color:#1e293b;\\">" + grp.tests[0].students[r].name + "</td>";',
    '      for (var t = 0; t < numTests; t++) {',
    '        var mark = grp.tests[t].students[r] ? grp.tests[t].students[r].mark : "-";',
    '        html += "<td style=\\"padding:10px 14px;border:1px solid #e2e8f0;text-align:center;font-weight:500;color:#2563eb;\\">" + mark + "</td>";',
    '      }',
    '      html += "</tr>";',
    '    }',
    '    html += "</tbody></table>";',
    '  }',
    '',
    '  html += "<p style=\\"color:#94a3b8;font-size:11px;margin:0;padding:10px 16px;background:#f8fafc;border-top:1px solid #e2e8f0;\\">MIE Faculty Attendance &bull; " + totalStudents + " student(s) &bull; " + selectedColumns.length + " test(s)</p>";',
    '  html += "</div>";',
    '  return html;',
    '}',
    '',
    'function syncToDashboard(sheet, lastCol) {',
    '  if (!WEBHOOK_URL || WEBHOOK_URL.indexOf("YOUR_BACKEND_URL") !== -1) return;',
    '  var sheetId = sheet.getParent().getId();',
    '  var sheetName = sheet.getName();',
    '  var columns = [];',
    '  for (var c = 2; c <= lastCol; c++) {',
    '    var testName = sheet.getRange(3, c).getValue();',
    '    if (!testName) continue;',
    '    var subjectName = sheet.getRange(2, c).getValue() || "";',
    '    var branchName = sheet.getRange(1, c).getValue() || "";',
    '    var isApproved = sheet.getRange(4, c).getValue() === true;',
    '    columns.push({ name: testName, subject: subjectName, branch: branchName, colIndex: c, approved: isApproved, approvedAt: isApproved ? new Date().toISOString() : null });',
    '  }',
    '  try {',
    '    UrlFetchApp.fetch(WEBHOOK_URL, { method: "post", contentType: "application/json", payload: JSON.stringify({ sheetId: sheetId, sheetName: sheetName, columns: columns }) });',
    '  } catch (err) {}',
    '}',
    '',
    'function testEmail() {',
    '  if (!STAFF_EMAIL || STAFF_EMAIL === "staff@example.com") { SpreadsheetApp.getUi().alert("Set STAFF_EMAIL first!"); return; }',
    '  MailApp.sendEmail({ to: STAFF_EMAIL, subject: "Test - MIE Faculty", htmlBody: "<div style=\\"font-family:Arial;padding:20px;\\"><h2 style=\\"color:#2563eb;\\">Test OK!</h2><p>Email works for " + LECTURER_NAME + ".</p></div>" });',
    '  SpreadsheetApp.getUi().alert("Test sent to " + STAFF_EMAIL);',
    '}',
  ].join('\n');
}
